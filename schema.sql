-- Execute no SQL Editor de um projeto Supabase novo.
create table if not exists public.books (
 id bigint generated by default as identity primary key,
 title text not null, author text not null, publisher text not null default 'Não informada',
 category text not null default 'Vida cristã', description text not null default '',
 cover_url text, sample_url text, sample_text text, price_cents integer not null default 0 check(price_cents>=0),
 stock integer not null default 0 check(stock>=0), featured boolean not null default false,
 published_at date, active boolean not null default true
);
create table if not exists public.staff (
 user_id uuid primary key references auth.users(id) on delete cascade,
 role text not null check(role in ('admin','staff'))
);
create table if not exists public.orders (
 id bigint generated always as identity primary key,
 created_at timestamptz not null default now(),
 book_id bigint not null references public.books(id), quantity integer not null default 1 check(quantity>0),
 unit_price_cents integer not null check(unit_price_cents>=0),
 customer_name text not null,
 delivery_type text not null check(delivery_type in ('mesa','balcao','presente')),
 table_number text, recipient_name text, recipient_address text, recipient_cep text, dedication text,
 payment_method text not null check(payment_method in ('caixa','pix','cartao')),
 payment_status text not null default 'pendente' check(payment_status in ('pendente','pago','cancelado')),
 status text not null default 'recebido' check(status in ('recebido','separando','pronto','entregue','enviado','cancelado'))
);
create or replace function public.is_staff() returns boolean language sql stable security definer set search_path = '' as $$
 select exists(select 1 from public.staff where user_id=(select auth.uid()));
$$;
revoke all on function public.is_staff() from public;
grant execute on function public.is_staff() to authenticated;
alter table public.books enable row level security;
alter table public.orders enable row level security;
alter table public.staff enable row level security;
revoke all on public.books,public.orders,public.staff from anon,authenticated;
grant select on public.books to anon,authenticated;
grant select,insert,update on public.books to authenticated;
grant select,update on public.orders to authenticated;
grant select on public.staff to authenticated;
create policy "public active books" on public.books for select to anon,authenticated using(active or public.is_staff());
create policy "staff add books" on public.books for insert to authenticated with check(public.is_staff());
create policy "staff edit books" on public.books for update to authenticated using(public.is_staff()) with check(public.is_staff());
create policy "staff read orders" on public.orders for select to authenticated using(public.is_staff());
create policy "staff update orders" on public.orders for update to authenticated using(public.is_staff()) with check(public.is_staff());
create policy "staff see staff" on public.staff for select to authenticated using(user_id=(select auth.uid()));
